export function translate(text: string, language: Language) {
  if (language === "en") return text;
  const suffix = text.endsWith(" ✓") ? " ✓" : "";
  const key = suffix ? text.slice(0, -2) : text;
  return (translations[key]?.[language === "zh-CN" ? 0 : 1] ?? key) + suffix;
}
